func TestGenerateConfigTool_Schema(t *testing.T) {
	tool := GenerateConfigTool()
	if tool.Name != "eidos/generate-config" {
		t.Errorf("tool name = %q, want eidos/generate-config", tool.Name)
	}
	if tool.Description == "" {
		t.Error("expected non-empty tool description")
	}
	schema, ok := tool.InputSchema.(*jsonschema.Schema)
	if !ok {
		t.Fatalf("expected InputSchema to be *jsonschema.Schema, got %T", tool.InputSchema)
	}
	if schema.Type != "object" {
		t.Errorf("expected input schema type object, got %q", schema.Type)
	}
	if len(schema.Required) != 1 || schema.Required[0] != "spec" {
		t.Errorf("expected required field [spec], got %v", schema.Required)
	}
	outputSchema, ok := tool.OutputSchema.(*jsonschema.Schema)
	if !ok {
		t.Fatalf("expected OutputSchema to be *jsonschema.Schema, got %T", tool.OutputSchema)
	}
	if outputSchema.Type != "object" {
		t.Errorf("expected output schema type object, got %q", outputSchema.Type)
	}
	for _, name := range []string{"config", "diagnostics", "valid"} {
		if _, present := outputSchema.Properties[name]; !present {
			t.Errorf("expected output property %q", name)
		}
	}
	if len(outputSchema.Required) != 3 || outputSchema.Required[0] != "config" || outputSchema.Required[1] != "diagnostics" || outputSchema.Required[2] != "valid" {
		t.Errorf("expected output required [config, diagnostics, valid], got %v", outputSchema.Required)
	}

	// Validate the schema definitions are well-formed and self-consistent.
	resolved, err := outputSchema.Resolve(nil)
	if err != nil {
		t.Fatalf("failed to resolve output schema: %v", err)
	}
	if err := resolved.Validate(map[string]any{
		"config":      "provider:\n  name: test\n",
		"diagnostics": []any{},
		"valid":       true,
	}); err != nil {
		t.Errorf("output schema rejected a valid result payload: %v", err)
	}

	diagItems := outputSchema.Properties["diagnostics"].Items
	for _, name := range []string{"severity", "summary"} {
		if _, present := diagItems.Properties[name]; !present {
			t.Errorf("expected diagnostic property %q", name)
		}
	}
	if len(diagItems.Required) != 2 || diagItems.Required[0] != "severity" || diagItems.Required[1] != "summary" {
		t.Errorf("expected diagnostic required [severity, summary], got %v", diagItems.Required)
	}
	severitySchema := diagItems.Properties["severity"]
	if len(severitySchema.Enum) != 3 {
		t.Errorf("expected severity enum with 3 values, got %v", severitySchema.Enum)
	}
	for _, want := range []string{"error", "warning", "info"} {
		found := false
		for _, v := range severitySchema.Enum {
			if v == want {
				found = true
				break
			}
		}
		if !found {
			t.Errorf("expected severity enum to contain %q, got %v", want, severitySchema.Enum)
		}
	}
	for _, name := range []string{"file", "line", "column", "path"} {
		if _, present := diagItems.Properties["source_location"].Properties[name]; !present {
			t.Errorf("expected source_location property %q", name)
		}
	}
}

