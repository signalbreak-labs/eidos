func parseResult(t *testing.T, result *mcp.CallToolResult) GenerateConfigResult {
	t.Helper()
	if len(result.Content) == 0 {
		t.Fatal("expected non-empty tool result content")
	}
	text, ok := result.Content[0].(*mcp.TextContent)
	if !ok {
		t.Fatalf("expected TextContent, got %T", result.Content[0])
	}
	var r GenerateConfigResult
	if err := json.Unmarshal([]byte(text.Text), &r); err != nil {
		t.Fatalf("failed to unmarshal tool result: %v\n%s", err, text.Text)
	}
	return r
}

func hasError(diags []api.DiagnosticJSON) bool {
	for _, d := range diags {
		if d.Severity == "error" {
			return true
		}
	}
	return false
}

