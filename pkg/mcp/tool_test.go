// TestNormalizeSpec_ByteishTypes covers the []byte and json.RawMessage branches
// of normalizeSpec, which the prior tests exercised only indirectly through the
// string path (L-73: these branches had no direct coverage).
func TestNormalizeSpec_ByteishTypes(t *testing.T) {
	const spec = `openapi: 3.0.0
info:
  title: Pet Store
  version: 1.0.0
paths: {}
`
	for _, name := range []string{"[]byte", "json.RawMessage"} {
		t.Run(name, func(t *testing.T) {
			var in any
			switch name {
			case "[]byte":
				in = []byte(spec)
			case "json.RawMessage":
				in = json.RawMessage(spec)
			}
			got, err := normalizeSpec(in)
			if err != nil {
				t.Fatalf("normalizeSpec(%s) error: %v", name, err)
			}
			if string(got) != spec {
				t.Errorf("normalizeSpec(%s) round-trip mismatch:\ngot:  %q\nwant: %q", name, string(got), spec)
			}
		})
	}
}

